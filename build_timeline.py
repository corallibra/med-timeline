def e(id, side, year, title, summary, people=None, works=None, archaeology=False,
      tags=None, confidence="high", sources=None, year_end=None, year_label=None):
    if year_label is None:
        if year < 0:
            if year_end is not None and year_end < 0:
                year_label = f"约前{abs(year)}–前{abs(year_end)}"
            elif year_end is not None and year_end > 0:
                year_label = f"约前{abs(year)}–{year_end}"
            else:
                year_label = f"约前{abs(year)}"
        else:
            if year_end is not None:
                year_label = f"{year}–{year_end}"
            else:
                year_label = str(year)
    return {
        "id": id,
        "side": side,
        "year": year,
        "yearEnd": year_end,
        "yearLabel": year_label,
        "title": title,
        "summary": summary,
        "people": people or [],
        "works": works or [],
        "archaeology": archaeology,
        "tags": tags or [],
        "confidence": confidence,
        "sources": sources or [],
    }

